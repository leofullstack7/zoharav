import type { Metadata } from "next";
import { getPathname } from "@/i18n/navigation";
import { routing } from "@/i18n/routing";
import { site } from "@/content/site";

const DEFAULT_OG_IMAGE = "/images/firm/office.svg";

/** Trims to a sentence boundary near `max` chars without inventing new copy. */
export function trimCopy(text: string, max = 160): string {
  if (text.length <= max) return text;
  const slice = text.slice(0, max);
  const lastStop = Math.max(slice.lastIndexOf(". "), slice.lastIndexOf("! "));
  if (lastStop > max * 0.4) return slice.slice(0, lastStop + 1).trim();
  const lastSpace = slice.lastIndexOf(" ");
  return `${slice.slice(0, lastSpace > 0 ? lastSpace : max).trim()}…`;
}

type PageSeoInput = {
  locale: string;
  /** Unprefixed canonical path, e.g. "/", "/about", "/services/energy-transition". */
  path: string;
  title: string;
  description: string;
  /** Bypasses the "%s · ZOHARAV & CO." title template (home page only). */
  absoluteTitle?: boolean;
  image?: string;
};

/**
 * Builds per-route Metadata (title, description, canonical, hreflang alternates,
 * OpenGraph, Twitter card) consistent with the Organization-level defaults set in
 * app/[locale]/layout.tsx. Pass locale-appropriate, already-translated strings —
 * this does not translate or invent copy, it only assembles the metadata shape.
 */
export function buildPageMetadata({
  locale,
  path,
  title,
  description,
  absoluteTitle,
  image,
}: PageSeoInput): Metadata {
  const languages: Record<string, string> = {};
  for (const loc of routing.locales) {
    languages[loc] = getPathname({ href: path, locale: loc });
  }
  const canonical = getPathname({ href: path, locale });
  /**
   * Social crawlers (Facebook/LinkedIn/X) generally don't render SVG for link
   * previews, so OG/Twitter images use a pre-rasterized PNG twin generated by
   * scripts/gen-og-fallbacks.cjs. On-page visuals stay SVG; only this metadata
   * path swaps to the raster fallback.
   */
  const ogImage = (image ?? DEFAULT_OG_IMAGE).replace(/\.svg$/, ".png");
  const ogLocale = locale === "es" ? "es_ES" : "en_US";

  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: {
      canonical,
      languages: {
        ...languages,
        "x-default": languages[routing.defaultLocale],
      },
    },
    openGraph: {
      title,
      description,
      url: canonical,
      siteName: site.name,
      locale: ogLocale,
      type: "website",
      images: [{ url: ogImage }],
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: [ogImage],
    },
  };
}
